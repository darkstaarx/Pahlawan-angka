#!/usr/bin/env node
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');

const root=path.resolve(__dirname,'..');
const output=path.join(root,'js','asset-manifest.js');
function manifest(){
  const files=[];
  function walk(dir){
    for(const entry of fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0)){
      const full=path.join(dir,entry.name);
      if(entry.isDirectory())walk(full);
      else if(entry.isFile()){
        const rel='./'+path.relative(root,full).split(path.sep).join('/');
        files.push([rel,crypto.createHash('sha256').update(fs.readFileSync(full)).digest('hex')]);
      }
    }
  }
  walk(path.join(root,'assets'));
  return files.sort((a,b)=>a[0]<b[0]?-1:a[0]>b[0]?1:0);
}
function source(entries){
  return `// Generated by tools/generate-asset-manifest.cjs. Do not edit by hand.\nself.PA_ASSET_MANIFEST=Object.freeze(${JSON.stringify(Object.fromEntries(entries),null,2)});\n`;
}
const expected=source(manifest());
if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==expected){console.error('Asset manifest is stale. Run node tools/generate-asset-manifest.cjs');process.exit(1)}
  console.log(`Asset manifest is current (${Object.keys(Object.fromEntries(manifest())).length} assets).`);
}else{
  fs.writeFileSync(output,expected);
  console.log(`Generated ${output} (${Object.keys(Object.fromEntries(manifest())).length} assets).`);
}
